"""End-to-end tests for the command line interface."""

import os
import subprocess
import sys
from pathlib import Path

import pytest

from gitignore_gen import __version__
from gitignore_gen.cli import main


def test_version_flag(capsys):
    with pytest.raises(SystemExit) as excinfo:
        main(["--version"])
    assert excinfo.value.code == 0
    assert __version__ in capsys.readouterr().out


def test_help_flag(capsys):
    with pytest.raises(SystemExit) as excinfo:
        main(["--help"])
    assert excinfo.value.code == 0
    out = capsys.readouterr().out
    assert "gitignore-gen" in out
    assert "detect" in out and "add" in out and "init" in out


def test_list_shows_all_templates(capsys):
    assert main(["list"]) == 0
    out = capsys.readouterr().out
    for name in ("python", "node", "go", "rust", "java", "terraform"):
        assert name in out
    assert "15 templates available" in out


def test_show_prints_template(capsys):
    assert main(["show", "python"]) == 0
    out = capsys.readouterr().out
    assert "__pycache__/" in out
    assert out.endswith("\n")


def test_show_unknown_template_exits_2(capsys):
    assert main(["show", "does-not-exist"]) == 2
    assert "unknown template" in capsys.readouterr().err


def test_detect_command_prints_suggestion(tmp_path, capsys):
    (tmp_path / "package.json").write_text("{}", encoding="utf-8")
    assert main(["detect", str(tmp_path)]) == 0
    out = capsys.readouterr().out
    assert "node" in out
    assert "gitignore-gen add node" in out


def test_add_command_writes_file(tmp_path, capsys):
    target = tmp_path / ".gitignore"
    assert main(["add", "python,node", "--output", str(target)]) == 0
    out = capsys.readouterr().out
    assert "Added" in out
    text = target.read_text(encoding="utf-8")
    assert text.startswith("# Generated by gitignore-gen")
    assert "node_modules/" in text


def test_add_dry_run_does_not_create_file(tmp_path, capsys):
    target = tmp_path / ".gitignore"
    assert main(["add", "go", "--output", str(target), "--dry-run"]) == 0
    out = capsys.readouterr().out
    assert "Would add" in out
    assert not target.exists()


def test_add_unknown_template_exits_2(tmp_path, capsys):
    target = tmp_path / ".gitignore"
    assert main(["add", "python,nope", "--output", str(target)]) == 2
    assert "unknown template" in capsys.readouterr().err
    assert not target.exists()


def test_init_end_to_end(tmp_path, capsys):
    (tmp_path / "app.py").write_text("print('hi')", encoding="utf-8")
    (tmp_path / "package.json").write_text("{}", encoding="utf-8")

    assert main(["init", str(tmp_path)]) == 0

    out = capsys.readouterr().out
    assert "Detected" in out
    assert "python" in out and "node" in out

    gitignore = tmp_path / ".gitignore"
    assert gitignore.is_file()
    text = gitignore.read_text(encoding="utf-8")
    assert "__pycache__/" in text
    assert "node_modules/" in text


def test_init_empty_directory_writes_nothing(tmp_path, capsys):
    assert main(["init", str(tmp_path)]) == 0
    assert "Nothing written" in capsys.readouterr().out
    assert not (tmp_path / ".gitignore").exists()


def test_python_m_gitignore_gen_version(tmp_path):
    """The documented ``python -m gitignore_gen`` invocation must work."""
    src = Path(__file__).resolve().parents[1] / "src"
    env = os.environ.copy()
    env["PYTHONPATH"] = str(src) + os.pathsep + env.get("PYTHONPATH", "")
    proc = subprocess.run(
        [sys.executable, "-m", "gitignore_gen", "--version"],
        cwd=str(tmp_path),
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    assert __version__ in proc.stdout
