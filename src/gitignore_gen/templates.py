#: Registry of all built-in templates, keyed by short name.
TEMPLATES: Dict[str, Template] = {
    t.name: t
    for t in (
        _PYTHON,
        _NODE,
        _GO,
        _RUST,
        _JAVA,
        _C,
        _CPP,
        _MACOS,
        _WINDOWS,
        _LINUX,
        _VSCODE,
        _JETBRAINS,
        _GIT,
        _DOCKER,
        _TERRAFORM,
    )
}


def get_template(name: str) -> Template:
    """Return the template registered under ``name``.

    Args:
        name: Template identifier, case-insensitive.

    Returns:
        The matching :class:`Template`.

    Raises:
        KeyError: If no template with that name exists.
    """
    key = name.strip().lower()
    if key not in TEMPLATES:
        raise KeyError(name)
    return TEMPLATES[key]


def template_names() -> List[str]:
    """Return all template names in stable registration order."""
    return list(TEMPLATES.keys())
