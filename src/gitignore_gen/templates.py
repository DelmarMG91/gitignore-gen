"""Curated, ready-to-use ``.gitignore`` templates.

Each template is a small, real-world accurate block of rules that can be merged
into a project ``.gitignore``. Templates are kept in a plain ``dict`` so callers
can enumerate, render, or extend them easily.

All content is pure data: ``# comment`` lines are preserved verbatim and glob
patterns (``*``, ``?``, ``[...]``, ``**``) follow the gitignore syntax.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Tuple


@dataclass(frozen=True)
class Template:
    """A single named ``.gitignore`` template.

    Attributes:
        name: Unique short identifier (e.g. ``"python"``).
        description: One-line human readable summary used by ``list``.
        lines: Ordered rule/comment lines. Stored without a trailing newline.
    """

    name: str
    description: str
    lines: Tuple[str, ...]

    def render(self) -> str:
        """Return the template as a newline-terminated string.

        Returns:
            The template body, guaranteed to end with exactly one ``\\n``.
        """
        body = "\n".join(self.lines).rstrip("\n")
        return body + "\n"


