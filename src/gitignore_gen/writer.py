"""Merging templates into a ``.gitignore`` file.

The writer is intentionally conservative: existing user content is never
deleted or reordered. New rules are appended only when they are not already
present, and the generated file always carries a provenance header.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, List, Sequence, Union

from .templates import TEMPLATES, Template, get_template

HEADER = "# Generated by gitignore-gen"


@dataclass
class WriteResult:
    """Outcome of a write operation.

    Attributes:
        path: Destination path as a string.
        added: Number of rule lines appended (or that would be appended in a
            dry run).
        total: Number of rule lines in the fully merged template selection.
        written: ``True`` if the file was actually modified.
        added_lines: The concrete lines that were added.
    """

    path: str
    added: int
    total: int
    written: bool
    added_lines: List[str] = field(default_factory=list)


def resolve_names(names: Iterable[str]) -> List[str]:
    """Normalise and validate a sequence of template names.

    Accepts comma-separated entries and mixed case. Duplicates are removed
    while preserving first-seen order.

    Args:
        names: Raw names, e.g. ``["python,node", "Go"]``.

    Returns:
        Normalised unique template names.

    Raises:
        KeyError: If any name is unknown.
    """
    resolved: List[str] = []
    for raw in names:
        for part in str(raw).split(","):
            name = part.strip().lower()
            if not name:
                continue
            get_template(name)  # raises KeyError for unknown names
            if name not in resolved:
                resolved.append(name)
    if not resolved:
        raise ValueError("at least one template name is required")
    return resolved


def merge_lines(names: Sequence[str]) -> List[str]:
    """Merge template bodies into a single de-duplicated line list.

    A line is considered a duplicate when its stripped form was already emitted
    by an earlier template. Blank lines are collapsed and trailing blanks
    trimmed, keeping the result readable.

    Args:
        names: Valid template names, in merge order.

    Returns:
        Merged lines without the provenance header.
    """
    out: List[str] = []
    seen: set[str] = set()
    for name in names:
        template = get_template(name)
        for line in template.lines:
            stripped = line.strip()
            if not stripped:
                if out and out[-1].strip() == "":
                    continue
                out.append("")
                continue
            if stripped in seen:
                continue
            seen.add(stripped)
            out.append(line)

    while out and out[-1].strip() == "":
        out.pop()
    return out


def render(names: Sequence[str]) -> str:
    """Render a brand-new ``.gitignore`` body for ``names``.

    Args:
        names: Valid template names.

    Returns:
        File content starting with :data:`HEADER`.
    """
    body = merge_lines(names)
    return HEADER + "\n\n" + "\n".join(body) + "\n"


def write_gitignore(
    output: Union[Path, str],
    names: Sequence[str],
    dry_run: bool = False,
) -> WriteResult:
    """Write or extend a ``.gitignore`` with the selected templates.

    If the target exists, its current lines are preserved verbatim; only rules
    that are missing are appended. If the file does not exist, a new file is
    created with the header.

    Args:
        output: Destination file path.
        names: Valid template names, in merge order.
        dry_run: When ``True``, compute the result but do not touch disk.

    Returns:
        A :class:`WriteResult` describing what was (or would be) written.

    Raises:
        IsADirectoryError: If ``output`` points at an existing directory.
        OSError: Propagated for filesystem failures.
    """
    path = Path(output)
    if path.exists() and path.is_dir():
        raise IsADirectoryError(f"output path is a directory: {path}")

    merged = merge_lines(names)
    exists = path.is_file()
    existing_lines: List[str] = []
    if exists:
        existing_lines = path.read_text(encoding="utf-8").splitlines()

    existing_seen = {line.strip() for line in existing_lines if line.strip()}
    has_header = any(line.strip() == HEADER for line in existing_lines)

    added_lines: List[str] = []
    for line in merged:
        stripped = line.strip()
        if not stripped:
            continue
        if stripped in existing_seen:
            continue
        existing_seen.add(stripped)
        added_lines.append(line)

    if dry_run:
        return WriteResult(
            path=str(path),
            added=len(added_lines),
            total=len(merged),
            written=False,
            added_lines=added_lines,
        )

    if not exists:
        content = render(names)
    else:
        lines = list(existing_lines)
        if not has_header:
            lines = [HEADER, ""] + lines
        if added_lines:
            if lines and lines[-1].strip() != "":
                lines.append("")
            lines.extend(added_lines)
        content = "\n".join(lines).rstrip("\n") + "\n"

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return WriteResult(
        path=str(path),
        added=len(added_lines),
        total=len(merged),
        written=True,
        added_lines=added_lines,
    )


def template_count() -> int:
    """Return the number of built-in templates."""
    return len(TEMPLATES)


def list_templates() -> List[Template]:
    """Return all templates in registration order."""
    return list(TEMPLATES.values())
